// The retrieval layer: code-built facts about a repository for agents and for
// orch itself, with no model and no run state. A ctxEnv is one checkout plus
// the tools that read it (jbcontext for concepts, gopls and the TypeScript 7
// server for symbols, rg for exact text) and a cache. `orch ctx` exposes it;
// the gate, `orch new` and `orch plan` are consumers.

const (
	ctxParallel = 6
	ctxKeepDays = 14 // cache states of older checkouts are removed
)

var (
	jbStatusLimit  = 30 * time.Second
	jbRefreshLimit = 120 * time.Second
	jbFullLimit    = 15 * time.Minute
)

type ctxOpts struct {
	Cfg     config
	Private bool     // private work: jbcontext is never called
	Skip    []string // repo-relative files left out of results (the spec itself)
}

type ctxEnv struct {
	Code     string
	ReadOnly bool
	CacheDir string
	JB       string
	Gopls    string
	RG       string
	Policy   string // full, incremental or off
	NoJB     bool   // private work, a denied repo or policy off
	NoJBWhy  string
	Skip     map[string]bool

	sem       chan struct{}
	mu        sync.Mutex
	notes     []string
	used      map[string]string
	trkOnce   sync.Once
	tracked   []string
	genMu     sync.Mutex
	genCache  map[string]bool // path -> generated by header or .gitattributes
	attrOnce  sync.Once
	attrRules []attrRule
	idxOnce   sync.Once
	idx       jbState
	editOnce  sync.Once
	edited    []string // files modified or untracked in this checkout

	lineCache map[string][]string
}

func newCtxEnv(code string, o ctxOpts) *ctxEnv {
	applyCtxLangs(o.Cfg.CtxLangs)
	e := &ctxEnv{Code: code, ReadOnly: ctxReadOnly(), JB: jbcontextBin(), Gopls: goplsBin(), RG: envOr("ORCH_RG", "rg"), Policy: o.Cfg.CtxIndex,
		CacheDir: ctxCacheDir(code), Skip: map[string]bool{}, sem: make(chan struct{}, ctxParallel), used: map[string]string{}}
	if e.Policy == "" {
		e.Policy = "full"
	}
	if p, err := exec.LookPath(e.Gopls); err == nil {
		if real, err := ctxServerBinary(code, p); err == nil {
			e.Gopls = real
		} else {
			e.Gopls = ""
			e.note(ctxServerSkip("gopls"))
		}
	}
	for _, s := range o.Skip {
		if s != "" {
			e.Skip[s] = true
		}
	}
	switch {
	case o.Private:
		e.NoJB, e.NoJBWhy = true, "jbcontext is not used for private work"
	case ctxDenied(code, o.Cfg.CtxDeny):
		e.NoJB, e.NoJBWhy = true, "jbcontext is not used in this repo (ctx_deny)"
	case e.Policy == "off":
		e.NoJB, e.NoJBWhy = true, "jbcontext is off (ctx_index = off)"
	}
	return e
}

// ctxDenied reports whether the checkout is one of the denied repositories.
func ctxDenied(code string, deny []string) bool {
	return len(deny) > 0 && ctxRepoListed(code, ctxRepoIdentity(code), deny)
}

// jbOK reports whether jbcontext may be called and exists.
func (e *ctxEnv) jbOK() bool {
	if e.NoJB {
		return false
	}
	_, err := exec.LookPath(e.JB)
	return err == nil
}

// jbMissing is the reason concept search is unavailable, or "".
func (e *ctxEnv) jbMissing() string {
	switch {
	case e.NoJB:
		return e.NoJBWhy
	case !e.jbOK():
		return "no concept search: " + e.JB + " was not found"
	}
	return ""
}

func (e *ctxEnv) note(s string) {
	e.mu.Lock()
	defer e.mu.Unlock()
	if slices.Contains(e.notes, s) {
		return
	}
	e.notes = append(e.notes, s)
}

// Notes returns what went wrong or may be stale, in the order it happened.
func (e *ctxEnv) Notes() []string {
	e.mu.Lock()
	defer e.mu.Unlock()
	return append([]string(nil), e.notes...)
}

func (e *ctxEnv) use(tool, detail string) {
	e.mu.Lock()
	e.used[tool] = detail
	e.mu.Unlock()
}

// parallel runs fn for every index with at most ctxParallel at once.
func (e *ctxEnv) parallel(n int, fn func(i int)) {
	var wg sync.WaitGroup
	for i := range n {
		wg.Add(1)
		e.sem <- struct{}{}
		go func(i int) {
			defer wg.Done()
			defer func() { <-e.sem }()
			fn(i)
		}(i)
	}
	wg.Wait()
}

// fanOut runs fn for every index with at most width at once, starting them in
// index order. It takes no slot of e.sem: for concept searches the width is the
// jbcontext slot cap and the slots themselves limit the processes.
func fanOut(width, n int, fn func(i int)) {
	if width < 1 {
		width = 1
	}
	next := make(chan int)
	var wg sync.WaitGroup
	for w := 0; w < min(width, n); w++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			for i := range next {
				fn(i)
			}
		}()
	}
	for i := range n {
		next <- i
	}
	close(next)
	wg.Wait()
}

// files lists the tracked files of the checkout.
func (e *ctxEnv) files() []string {
	e.trkOnce.Do(func() {
		// Tracked files, plus untracked ones git does not ignore; never an ignored file.
		if out, err := git(e.Code, "ls-files", "--cached", "--others", "--exclude-standard"); err == nil && out != "" {
			for _, path := range strings.Split(out, "\n") {
				if !e.ReadOnly || ctxWithinRoot(e.Code, path) {
					e.tracked = append(e.tracked, path)
				}
			}
		}
	})
	return e.tracked
}

// ---- cache ----

// ctxCacheDir is where the results for this state of the checkout are kept:
// <cache>/ctx/<repo hash>/<HEAD>-<dirty hash>. A new commit or a different
// uncommitted change is a new directory, so a cached answer is never served for
// code it was not computed on.
func ctxCacheDir(code string) string {
	root := os.Getenv("ORCH_CACHE_DIR")
	if root == "" {
		home, _ := os.UserHomeDir()
		root = filepath.Join(home, ".cache", "orchestrate")
	}
	repo := sha256.Sum256([]byte(evalOr(code)))
	base := filepath.Join(root, "ctx", fmt.Sprintf("%x", repo[:6]))
	head, err := git(code, "rev-parse", "HEAD")
	if err != nil || head == "" {
		return filepath.Join(base, "nogit")
	}
	dir := filepath.Join(base, head[:min(12, len(head))]+"-"+ctxDirtyHash(code))
	pruneCtxCache(base, dir)
	return dir
}

// ctxDirtyHash hashes the uncommitted diff and the untracked files (name, size
// and modification time); "clean" when there is none.
func ctxDirtyHash(code string) string {
	diff, _ := git(code, "diff", "HEAD")
	untracked, _ := git(code, "ls-files", "--others", "--exclude-standard")
	if diff == "" && untracked == "" {
		return "clean"
	}
	h := sha256.New()
	h.Write([]byte(diff))
	names := strings.Split(untracked, "\n")
	sort.Strings(names)
	for i, n := range names {
		if i == 5000 {
			break
		}
		if st, err := os.Stat(filepath.Join(code, n)); err == nil {
			fmt.Fprintf(h, "\x00%s:%d:%d", n, st.Size(), st.ModTime().UnixNano())
		}
	}
	return fmt.Sprintf("%x", h.Sum(nil)[:4])
}

func pruneCtxCache(base, keep string) {
	entries, err := os.ReadDir(base)
	if err != nil {
		return
	}
	for _, en := range entries {
		p := filepath.Join(base, en.Name())
		if p == keep {
			continue
		}
		if info, err := en.Info(); err == nil && time.Since(info.ModTime()) > ctxKeepDays*24*time.Hour {
			_ = os.RemoveAll(p)
		}
	}
}

// ---- index freshness ----

// jbState is what the first look at the index of a run found.
type jbState struct {
	rev    string // pass as --revision; empty when HEAD is not indexed
	indexd string // newest indexed revision, if any
	head   string
	dirty  bool
	note   string // set when hits may be stale
}

// Ready checks the index once per env, refreshing it as the policy allows.
func (e *ctxEnv) Ready() jbState {
	e.idxOnce.Do(func() { e.idx = e.checkIndex(false) })
	return e.idx
}

// jbRev is the revision searches are pinned to.
func (e *ctxEnv) jbRev() string {
	if e.NoJB {
		return ""
	}
	return e.Ready().rev
}

// jbIndexed lists the indexed revisions, newest first.
func (e *ctxEnv) jbIndexed() ([]string, bool) {
	ctx, cancel := context.WithTimeout(context.Background(), jbStatusLimit)
	defer cancel()
	cmd := exec.CommandContext(ctx, e.JB, "status", "--json-output", "--project-path", e.Code)
	cmd.Dir = e.Code
	out, err := cmd.Output()
	if err != nil {
		return nil, false
	}
	var st struct {
		Type    string `json:"type"`
		Indices []struct {
			Snapshots []struct {
				Revision  string `json:"revision"`
				CreatedAt int64  `json:"createdAt"`
			} `json:"snapshots"`
		} `json:"indices"`
	}
	if json.NewDecoder(strings.NewReader(string(out))).Decode(&st) != nil || st.Type != "status_result" {
		return nil, false
	}
	type snap struct {
		rev string
		at  int64
	}
	var all []snap
	for _, ix := range st.Indices {
		for _, s := range ix.Snapshots {
			all = append(all, snap{s.Revision, s.CreatedAt})
		}
	}
	sort.SliceStable(all, func(i, j int) bool { return all[i].at > all[j].at })
	var revs []string
	for _, s := range all {
		revs = append(revs, s.rev)
	}
	return revs, true
}

func sha7(s string) string { return s[:min(7, len(s))] }

// checkIndex looks at the index and makes it current as far as the policy
// allows: a missing index is built only under `full` (or when forceFull asks
// for it), a stale one is refreshed incrementally, and `off` or a denied repo
// never reach jbcontext. Searches are pinned to HEAD when it is indexed.
func (e *ctxEnv) checkIndex(forceFull bool) jbState {
	if e.jbMissing() != "" {
		return jbState{}
	}
	head, err := git(e.Code, "rev-parse", "HEAD")
	if err != nil || head == "" {
		return jbState{}
	}
	porcelain, _ := git(e.Code, "status", "--porcelain")
	st := jbState{head: head, dirty: strings.TrimSpace(porcelain) != ""}
	revs, ok := e.jbIndexed()
	if !ok {
		return jbState{} // the searches will say what is wrong
	}
	has := func(revs []string) bool {
		return slices.Contains(revs, head)
	}
	refreshErr := ""
	run := func(limit time.Duration, args ...string) {
		ctx, cancel := context.WithTimeout(context.Background(), limit)
		defer cancel()
		cmd := exec.CommandContext(ctx, e.JB, args...)
		cmd.Dir = e.Code
		if err := cmd.Run(); err != nil {
			refreshErr = err.Error()
			if ctx.Err() != nil {
				refreshErr = fmt.Sprintf("timed out after %s", limit)
			}
		}
	}
	if !has(revs) && e.ReadOnly {
		e.note("read-only ctx: index builds and refreshes are disabled; run orch ctx refresh outside this session")
	}
	if !has(revs) && !e.ReadOnly {
		switch {
		case len(revs) == 0 && (e.Policy == "full" || forceFull):
			e.note("jbcontext: this repo has no index, so a full index was started (up to " + jbFullLimit.String() + ")")
			run(jbFullLimit, "index", "--project-path", e.Code)
		case len(revs) == 0:
			e.note("jbcontext has no index for this repo and ctx_index is incremental: run `orch ctx refresh --full`")
		default:
			run(jbRefreshLimit, "index", "--only-incremental", "--silent", "--project-path", e.Code)
		}
		if again, ok := e.jbIndexed(); ok {
			revs = again
		}
	}
	if len(revs) > 0 {
		st.indexd = revs[0]
	}
	if has(revs) {
		st.rev, st.indexd = head, head
	}
	if st.rev == "" || st.dirty {
		at := st.indexd
		if at == "" {
			at = "none"
		}
		st.note = fmt.Sprintf("jbcontext index is at %s, working tree is at %s", sha7(at), sha7(head))
		if st.dirty {
			st.note += " with uncommitted changes"
		}
		st.note += ": hits may be stale"
		if refreshErr != "" {
			st.note += " (index refresh failed: " + refreshErr + ")"
		}
	}
	return st
}

// editedFiles lists the files modified or untracked in this checkout, once.
// jbcontext does not reliably see uncommitted content, so the agent is told
// which files to read from disk.
func (e *ctxEnv) editedFiles() []string {
	e.editOnce.Do(func() {
		cmd := exec.Command("git", "status", "--porcelain=v1", "-z", "--untracked-files=all")
		cmd.Dir = e.Code
		out, err := cmd.Output() // not git(): its trimming eats the first status column
		if err != nil {
			return
		}
		for _, rec := range strings.Split(string(out), "\x00") {
			if len(rec) > 3 && rec[0] != 'D' && rec[1] != 'D' {
				e.edited = append(e.edited, rec[3:])
			}
		}
		sort.Strings(e.edited)
	})
	return e.edited
}

// Refresh runs the index check now (for `orch ctx refresh`) and returns it.
func (e *ctxEnv) Refresh(forceFull bool) jbState {
	e.idxOnce.Do(func() {})
	e.idx = e.checkIndex(forceFull)
	return e.idx
}

// withIndexNote adds the staleness note of the index, if any, once searches ran.
func (e *ctxEnv) indexNote() {
	if e.NoJB || !e.jbOK() {
		return
	}
	if st := e.Ready(); st.note != "" {
		e.note(st.note)
	}
}

// Sources names the tools that answered and any staleness, for the last line
// of every `orch ctx` output.
func (e *ctxEnv) Sources() string { return e.sources(false) }

// SourcesBrief is Sources for a model reader: the tool names and any staleness
// or tier note, without the path of the binary that ran.
func (e *ctxEnv) SourcesBrief() string { return e.sources(true) }

func (e *ctxEnv) sources(brief bool) string {
	e.mu.Lock()
	var parts []string
	for tool, detail := range e.used {
		d := sourceDetail(tool, detail)
		if brief && (strings.HasPrefix(d, "/") || strings.HasPrefix(d, "~/")) {
			parts = append(parts, tool)
			continue
		}
		parts = append(parts, tool+" "+d)
	}
	e.mu.Unlock()
	sort.Strings(parts)
	if len(parts) == 0 {
		parts = []string{"none"}
	}
	return strings.Join(parts, "; ")
}

var tsVersionRe = regexp.MustCompile(`typescript-[a-z0-9]+-[a-z0-9]+@(\d[\w.]*)`)

// sourceDetail shortens a tool path for the sources line.
func sourceDetail(tool, detail string) string {
	if tool == "ts server" {
		if m := tsVersionRe.FindStringSubmatch(detail); m != nil {
			return "native " + m[1]
		}
	}
	return homePath(detail)
}
